-- Brings an existing IncidentFlow dev database up to the schema the Tier 1
-- feature work expects. Written by hand because this project creates its
-- schema with EnsureCreatedAsync(), which only ever creates tables from
-- scratch and silently leaves an existing database alone.
--
-- Everything is in one transaction: either the whole schema moves forward or
-- nothing does, so a failure halfway through cannot leave the database in a
-- state that matches neither the old code nor the new.
BEGIN;

-- ---- Incidents: the new columns ----------------------------------------
ALTER TABLE "Incidents"
  ADD COLUMN "DepartmentId"    integer,
  ADD COLUMN "CommanderUserId" integer,
  ADD COLUMN "AcknowledgedAt"  timestamp with time zone,
  ADD COLUMN "AcknowledgedBy"  integer,
  ADD COLUMN "EscalatedAt"     timestamp with time zone,
  ADD COLUMN "ResolvedAt"      timestamp with time zone,
  ADD COLUMN "SlaBreachedAt"   timestamp with time zone;

-- DepartmentId is NOT NULL in the model, so existing rows need a value
-- before the constraint can go on. The creator's own department is the
-- honest guess: you report problems about the systems you work on.
UPDATE "Incidents" i
SET "DepartmentId" = u."DepartmentId"
FROM "Users" u
WHERE u."Id" = i."CreatedBy"
  AND i."DepartmentId" IS NULL;

-- Belt and braces for any incident whose creator somehow has no department:
-- park it in the lowest-numbered one rather than failing the migration.
UPDATE "Incidents"
SET "DepartmentId" = (SELECT MIN("Id") FROM "Departments")
WHERE "DepartmentId" IS NULL;

ALTER TABLE "Incidents" ALTER COLUMN "DepartmentId" SET NOT NULL;

-- Already-resolved incidents predate the ResolvedAt column, so they would
-- otherwise read as "resolved, but never resolved at any particular time".
-- UpdatedAt is the closest thing to the truth we have on record.
UPDATE "Incidents"
SET "ResolvedAt" = "UpdatedAt"
WHERE "Status" = 'RESOLVED'
  AND "ResolvedAt" IS NULL;

-- ---- Incidents: indexes and foreign keys -------------------------------
-- Names follow EF Core's own convention (IX_Table_Column,
-- FK_Table_OtherTable_Column) so this database looks exactly like one EF
-- created itself - which matters the day somebody does recreate it.
CREATE INDEX "IX_Incidents_DepartmentId"    ON "Incidents" ("DepartmentId");
CREATE INDEX "IX_Incidents_CommanderUserId" ON "Incidents" ("CommanderUserId");
CREATE INDEX "IX_Incidents_AcknowledgedBy"  ON "Incidents" ("AcknowledgedBy");

ALTER TABLE "Incidents"
  ADD CONSTRAINT "FK_Incidents_Departments_DepartmentId"
    FOREIGN KEY ("DepartmentId") REFERENCES "Departments"("Id") ON DELETE RESTRICT,
  ADD CONSTRAINT "FK_Incidents_Users_CommanderUserId"
    FOREIGN KEY ("CommanderUserId") REFERENCES "Users"("Id") ON DELETE RESTRICT,
  ADD CONSTRAINT "FK_Incidents_Users_AcknowledgedBy"
    FOREIGN KEY ("AcknowledgedBy") REFERENCES "Users"("Id") ON DELETE RESTRICT;

-- ---- Comments: the new table -------------------------------------------
CREATE TABLE "Comments" (
    "Id"         integer GENERATED BY DEFAULT AS IDENTITY,
    "IncidentId" integer NOT NULL,
    "UserId"     integer NOT NULL,
    "Body"       text    NOT NULL,
    "CreatedAt"  timestamp with time zone NOT NULL,
    CONSTRAINT "PK_Comments" PRIMARY KEY ("Id"),
    -- Deleting an incident takes its conversation with it...
    CONSTRAINT "FK_Comments_Incidents_IncidentId"
      FOREIGN KEY ("IncidentId") REFERENCES "Incidents"("Id") ON DELETE CASCADE,
    -- ...but deleting a user who has spoken is refused, so the history never
    -- ends up with messages from nobody.
    CONSTRAINT "FK_Comments_Users_UserId"
      FOREIGN KEY ("UserId") REFERENCES "Users"("Id") ON DELETE RESTRICT
);

-- The thread is always read as "this incident's comments, in order", so that
-- is the index the one real query wants.
CREATE INDEX "IX_Comments_IncidentId_CreatedAt" ON "Comments" ("IncidentId", "CreatedAt");
CREATE INDEX "IX_Comments_UserId"               ON "Comments" ("UserId");

COMMIT;
