// Authentication endpoints: register, login, and "who am I" (/me). This is
// the only file that creates JWT tokens or checks passwords - everything
// else just relies on CurrentUser.RequireAsync to know who's calling.
using IncidentFlow.Api.Common;
using IncidentFlow.Api.Data;
using IncidentFlow.Api.Dtos;
using IncidentFlow.Api.Entities;
using IncidentFlow.Api.Security;

namespace IncidentFlow.Api.Endpoints;

public static class AuthEndpoints
{
    public static void MapAuthEndpoints(this IEndpointRouteBuilder app)
    {
        // MapGroup("/api/auth") means every route below is actually mounted
        // at /api/auth/register, /api/auth/login, etc.
        var group = app.MapGroup("/api/auth").WithTags("auth");

        group.MapPost("/register", async (UserCreate payload, AppDbContext db) =>
        {
            if (!EmailValidation.IsValid(payload.Email))
            {
                throw ApiException.UnprocessableEntity("Invalid email address");
            }

            // Enforce one account per email address.
            var existing = await CurrentUser.FindByEmailAsync(db, payload.Email);
            if (existing is not null)
            {
                throw ApiException.BadRequest("Email already registered");
            }

            // Never store payload.Password directly - only the bcrypt hash of it.
            var user = new User
            {
                Email = payload.Email,
                Name = payload.Name,
                HashedPassword = PasswordHasher.Hash(payload.Password),
            };
            db.Users.Add(user);
            await db.SaveChangesAsync(); // assigns user.Id, generated by Postgres

            return Results.Json(new UserOut(user.Id, user.Email, user.Name), statusCode: StatusCodes.Status201Created);
        });

        group.MapPost("/login", async (UserLogin payload, AppDbContext db, JwtService jwt) =>
        {
            var user = await CurrentUser.FindByEmailAsync(db, payload.Email);
            if (user is null || !PasswordHasher.Verify(payload.Password, user.HashedPassword))
            {
                // Deliberately vague error message - we don't want to reveal
                // whether the email exists but the password was wrong, or the
                // email doesn't exist at all. That distinction would help an
                // attacker enumerate accounts.
                throw ApiException.Unauthorized("Invalid email or password");
            }

            return Results.Ok(new TokenResponse(jwt.CreateAccessToken(user.Email)));
        });

        group.MapGet("/me", async (HttpContext context, AppDbContext db, JwtService jwt) =>
        {
            // Lets the frontend ask "who is currently logged in?" using just
            // the stored JWT - used on page load to restore the session
            // without asking the user to log in again.
            var user = await CurrentUser.RequireAsync(context, db, jwt);
            return Results.Ok(new UserOut(user.Id, user.Email, user.Name));
        });
    }
}
