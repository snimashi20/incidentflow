// Authentication endpoints: register, login, and "who am I" (/me). This is
// the only file that creates JWT tokens or checks passwords - everything
// else just relies on CurrentUser.RequireAsync to know who's calling.
using IncidentFlow.Api.Common;
using IncidentFlow.Api.Data;
using IncidentFlow.Api.Dtos;
using IncidentFlow.Api.Entities;
using IncidentFlow.Api.Security;
using Microsoft.EntityFrameworkCore;

namespace IncidentFlow.Api.Endpoints;

public static class AuthEndpoints
{
    public static void MapAuthEndpoints(this IEndpointRouteBuilder app)
    {
        // MapGroup("/api/auth") means every route below is actually mounted
        // at /api/auth/register, /api/auth/login, etc.
        var group = app.MapGroup("/api/auth").WithTags("auth");

        group.MapPost("/register", async (UserCreate payload, AppDbContext db) =>
        {
            if (!EmailValidation.IsValid(payload.Email))
            {
                throw ApiException.UnprocessableEntity("Invalid email address");
            }

            // Checked before anything touches the database. Until this
            // endpoint had a password rule at all, an empty string was a
            // perfectly acceptable password here. See Common/PasswordPolicy.cs
            // for why the rule is only about length.
            var passwordProblem = PasswordPolicy.Validate(payload.Password);
            if (passwordProblem is not null)
            {
                throw ApiException.UnprocessableEntity(passwordProblem);
            }

            // Enforce one account per email address.
            var existing = await CurrentUser.FindByEmailAsync(db, payload.Email);
            if (existing is not null)
            {
                throw ApiException.BadRequest("Email already registered");
            }

            // Every employee must belong to a real department, so check the
            // id we were given actually exists before trying to insert -
            // otherwise Postgres would reject the row with a foreign-key
            // error that means nothing to whoever filled in the form.
            var department = await db.Departments.FirstOrDefaultAsync(d => d.Id == payload.DepartmentId);
            if (department is null)
            {
                throw ApiException.UnprocessableEntity("Please choose a department you work in");
            }

            // Seniority arrives as text, so parse it into the enum here and
            // reject anything that isn't a real level. Enum.TryParse with
            // ignoreCase: true accepts "director" as well as "DIRECTOR".
            var seniority = Seniority.MID;
            if (!string.IsNullOrWhiteSpace(payload.Seniority)
                && !Enum.TryParse(payload.Seniority, ignoreCase: true, out seniority))
            {
                throw ApiException.UnprocessableEntity(
                    $"Unknown seniority level. Expected one of: {string.Join(", ", Enum.GetNames<Seniority>())}"
                );
            }

            // Never store payload.Password directly - only the bcrypt hash of it.
            var user = new User
            {
                Email = payload.Email,
                Name = payload.Name,
                HashedPassword = PasswordHasher.Hash(payload.Password),
                DepartmentId = department.Id,
                Seniority = seniority,
                // Job title is optional on the form - an empty string just
                // means "not given yet", which the UI simply doesn't show.
                JobTitle = payload.JobTitle?.Trim() ?? string.Empty,
            };
            db.Users.Add(user);
            await db.SaveChangesAsync(); // assigns user.Id, generated by Postgres

            // Set by hand because we built `user` ourselves rather than
            // loading it back with .Include(u => u.Department) - without
            // this, UserOut.From would hit a null Department.
            user.Department = department;

            return Results.Json(UserOut.From(user), statusCode: StatusCodes.Status201Created);
        });

        group.MapPost("/login", async (UserLogin payload, AppDbContext db, JwtService jwt) =>
        {
            var user = await CurrentUser.FindByEmailAsync(db, payload.Email);
            if (user is null || !PasswordHasher.Verify(payload.Password, user.HashedPassword))
            {
                // Deliberately vague error message - we don't want to reveal
                // whether the email exists but the password was wrong, or the
                // email doesn't exist at all. That distinction would help an
                // attacker enumerate accounts.
                throw ApiException.Unauthorized("Invalid email or password");
            }

            return Results.Ok(new TokenResponse(jwt.CreateAccessToken(user.Email)));
        })
        // Rate limited per IP address. Without this, /login is an unlimited
        // password-guessing endpoint: nothing stops a script trying ten
        // thousand passwords against one account. See Program.cs for the
        // policy itself - a fixed number of attempts per minute, which no
        // real person ever hits and a brute-force script hits immediately.
        .RequireRateLimiting(RateLimitPolicies.Login);

        // Hands out a short-lived, single-use ticket for opening a WebSocket.
        //
        // This exists because a browser cannot send an Authorization header
        // on a WebSocket handshake, so something has to go in the URL - and
        // URLs end up in access logs, proxy logs and browser history. This
        // endpoint is a normal authenticated request (token in the header,
        // where it belongs) that returns a 30-second throwaway credential to
        // put in the socket URL instead. See
        // Security/WebSocketTicketStore.cs.
        group.MapPost("/ws-ticket", async (
            HttpContext context, AppDbContext db, JwtService jwt, IWebSocketTicketStore tickets
        ) =>
        {
            var user = await CurrentUser.RequireAsync(context, db, jwt);
            var ticket = await tickets.IssueAsync(user.Email);

            return Results.Ok(new WebSocketTicketResponse(ticket, (int)WebSocketTicket.Lifetime.TotalSeconds));
        });

        group.MapGet("/me", async (HttpContext context, AppDbContext db, JwtService jwt) =>
        {
            // Lets the frontend ask "who is currently logged in?" using just
            // the stored JWT - used on page load to restore the session
            // without asking the user to log in again.
            var user = await CurrentUser.RequireAsync(context, db, jwt);

            // RequireAsync doesn't load the department (most callers don't
            // need it), so fetch it here before mapping to the full UserOut.
            await db.Entry(user).Reference(u => u.Department).LoadAsync();

            return Results.Ok(UserOut.From(user));
        });
    }
}
